-- The uploaded files themselves, so they survive the host wiping its disk.
-- document_files keeps the type and size; the bytes are in
-- document_file_chunks (document_files.data is '' then), or, for files
-- saved before chunking, in document_files.data.
CREATE TABLE IF NOT EXISTS document_files (
    document_id  integer      PRIMARY KEY REFERENCES documents (document_id) ON DELETE CASCADE,
    mime_type    varchar(100) NOT NULL,
    file_size    integer      NOT NULL,
    data         bytea        NOT NULL,
    stored_at    timestamp(0) DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS document_file_chunks (
    document_id  integer NOT NULL REFERENCES documents (document_id) ON DELETE CASCADE,
    seq          integer NOT NULL,   -- 0, 1, 2, ... in file order
    data         bytea   NOT NULL,
    PRIMARY KEY (document_id, seq)
);

