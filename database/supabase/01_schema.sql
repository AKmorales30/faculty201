    user_id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role                  varchar(20)  NOT NULL CHECK (role IN ('admin', 'faculty', 'program_chair', 'dean')),
    full_name             varchar(150) NOT NULL,
    name_title            varchar(20)  NULL,          -- Dr., Engr., Prof. ...
    first_name            varchar(60)  NULL,
    middle_name           varchar(60)  NULL,
    last_name             varchar(60)  NULL,
    name_suffix           varchar(10)  NULL,          -- Jr., Sr., III ...
    email                 varchar(150) NOT NULL UNIQUE,
    profile_picture       varchar(64)  NULL,
    employee_id           varchar(30)  NULL,
    contact_number        varchar(30)  NULL,
    password_hash         varchar(255) NOT NULL,
    must_change_password  smallint     NOT NULL DEFAULT 0,
    password_changed_at   timestamp(0) NULL,
    employment_type       varchar(20)  NULL CHECK (employment_type IN ('full_time', 'part_time')),
    academic_rank         varchar(60)  NULL,
    specialization        varchar(150) NULL,
    program               varchar(20)  NULL,
    college               varchar(20)  NULL,
    employment_status     varchar(20)  NULL DEFAULT 'active' CHECK (employment_status IN ('active', 'paused')),
    date_engaged          date         NULL,
    is_active             smallint     NOT NULL DEFAULT 1,
    created_at            timestamp(0) DEFAULT CURRENT_TIMESTAMP,
    updated_at            timestamp(0) DEFAULT CURRENT_TIMESTAMP,
    deleted_at            timestamp(0) NULL,          -- deleted from Manage Faculty, restorable for DELETED_RETENTION_DAYS
    deleted_by            integer      NULL,
    delete_reason         varchar(255) NULL,
    active_before_delete  smallint     NULL,          -- is_active to restore
    purged_at             timestamp(0) NULL           -- deleted permanently by the daily cleanup
);
