-- =====================================================================
-- Faculty-201 File Management System -- PostgreSQL schema for Supabase
--
-- The final state of database/schema.sql + every database/migration_*.sql,
-- rewritten for PostgreSQL. Same table and column names as the MySQL
-- database, so the data can be copied over as is.
--
-- How to run: Supabase dashboard > SQL Editor > New query, paste this
-- whole file, Run. Safe to run again (IF NOT EXISTS everywhere).
-- Then, for a fresh database: 02_seed_demo_accounts.sql (demo logins).
-- After copying data over from the old MySQL database instead:
-- 03_after_data_import.sql.
--
-- Translated from MySQL:
--   INT AUTO_INCREMENT       -> integer GENERATED BY DEFAULT AS IDENTITY
--   ENUM(...)                -> varchar + CHECK (the same values)
--   TINYINT(1) / TINYINT     -> smallint (the code compares with 0 / 1)
--   DATETIME / TIMESTAMP     -> timestamp(0): Philippine local time, no
--                               fractions, read back as 'Y-m-d H:i:s' like MySQL
--   LONGTEXT / MEDIUMTEXT    -> text
--   LONGBLOB / MEDIUMBLOB    -> bytea
--   JSON                     -> jsonb
--   ON UPDATE CURRENT_TIMESTAMP -> trigger set_updated_at()
-- Left out: ai_chat_messages (the chatbot was removed,
-- database/drop_ai_chatbot.sql).
-- =====================================================================

BEGIN;

-- NOW(), CURRENT_DATE and the timestamp defaults in Philippine time, the
-- same as PHP (config/config.php). config/db.php also sets it for every
-- connection.
ALTER DATABASE postgres SET timezone TO 'Asia/Manila';
SET LOCAL timezone TO 'Asia/Manila';

-- MySQL's ON UPDATE CURRENT_TIMESTAMP: updated_at becomes the current time
-- on every update, unless the update sets it itself.
CREATE OR REPLACE FUNCTION public.set_updated_at() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
        NEW.updated_at := CURRENT_TIMESTAMP;
    END IF;
    RETURN NEW;
END
$$;

