-- ------------------------------------------------------------- lock out Supabase's public API
-- Supabase serves every table in "public" over its REST API to anyone with
-- the project's anon key -- users.password_hash included. This system
-- never uses that API (PHP connects to the database directly, as the
-- table owner, which row level security doesn't apply to), so: row level
-- security on with no policies, and no table rights for the API roles.
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'users', 'employment_history', 'submission_requests', 'documents', 'document_files', 'document_file_chunks',
        'notifications', 'login_attempts', 'login_lockouts', 'security_alerts', 'activity_logs', 'expiration_alerts_sent',
        'system_settings', 'pds_records', 'pds_learning_development', 'pds_snapshots', 'pds_versions', 'academic_ranks',
        'profile_pictures', 'ai_reports', 'ai_usage_log', 'ai_reminders', 'ai_reminder_checks', 'schema_migrations'
    ] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated', t);
    END LOOP;
END
$$;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.set_updated_at() FROM PUBLIC, anon, authenticated;

COMMIT;
