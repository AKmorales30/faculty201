-- =====================================================================
-- Username login + email two-factor codes (PostgreSQL / Supabase)
--
-- Run in Supabase: SQL Editor > New query, paste this file, Run. Safe to
-- run again. For a new database: after 01_schema.sql (and 02 / 03).
-- The MySQL / MariaDB version is database/migration_username_2fa.sql
-- (applied automatically by the app).
--
--   users.username           what people log in with (set by the Admin);
--                            stored in lowercase, unique ignoring case
--   users.email              now the two-factor email: optional, and used
--                            only once email_verified_at is set
--   login_attempts.username  the username typed (email stays for old rows)
--   login_otps               one-time codes: login, setting up / changing
--                            the email, password reset (hashed, never plain)
--
-- Existing accounts get a username automatically (first.last, a number
-- added if taken) the first time the app needs one -- a login attempt or
-- the Admin opening Manage Faculty. To see them afterwards:
--   SELECT user_id, username, full_name, role FROM users ORDER BY user_id;
-- =====================================================================

BEGIN;

ALTER TABLE users ADD COLUMN IF NOT EXISTS username varchar(30) NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at timestamp(0) NULL;
ALTER TABLE users ALTER COLUMN email DROP NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username_lower ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower ON users (lower(email));
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_users_username_format') THEN
        ALTER TABLE users ADD CONSTRAINT ck_users_username_format CHECK (username ~ '^[a-z0-9._]{4,30}$');
    END IF;
END
$$;

ALTER TABLE login_attempts ADD COLUMN IF NOT EXISTS username varchar(150) NULL;
ALTER TABLE login_attempts ALTER COLUMN email DROP NOT NULL;
CREATE INDEX IF NOT EXISTS idx_login_attempts_username ON login_attempts (username, attempted_at);

CREATE TABLE IF NOT EXISTS login_otps (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       integer      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    purpose       varchar(20)  NOT NULL CHECK (purpose IN ('login', 'setup_email', 'change_email', 'reset_password')),
    email         varchar(150) NOT NULL,          -- where the code was sent
    code_hash     varchar(255) NOT NULL,          -- password_hash() of the 6 digits
    attempts      smallint     NOT NULL DEFAULT 0,
    sent_count    smallint     NOT NULL DEFAULT 1,
    ip_address    varchar(45)  NULL,
    created_at    timestamp(0) DEFAULT CURRENT_TIMESTAMP,
    last_sent_at  timestamp(0) NOT NULL,
    expires_at    timestamp(0) NOT NULL,
    used_at       timestamp(0) NULL               -- verified, replaced or cancelled: never accepted again
);
CREATE INDEX IF NOT EXISTS idx_login_otps_user ON login_otps (user_id, purpose, created_at);

-- Same API lockout as every other table (01_schema.sql)
ALTER TABLE login_otps ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE login_otps FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;

INSERT INTO schema_migrations (name) VALUES ('migration_username_2fa.sql') ON CONFLICT (name) DO NOTHING;

COMMIT;
